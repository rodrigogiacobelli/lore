# The second door to the same room — a recorded answer Lore cannot read
# ---------------------------------------------------------------------------
#
# Smoke round 7, N1. The empty-agent guard tells "explicitly no agent" apart
# from "nobody said", and one of its two ways of saying "explicitly" is an
# empty list recorded in `.lore/config.toml`. It tested `config.recorded_keys`
# — presence of the key — while the value came from `load_config`, which is
# fail-soft and coerces anything unusable to the built-in default `[]`. So a
# config Lore could not parse landed in the branch reserved for a deliberate
# choice, and one typo uninstalled every skill on exit 0.
#
# Two properties, because guarding each route one at a time is how the same
# outcome was reached twice: a value the loader threw away is not an answer,
# and — whatever produced it — a plan that uninstalls everything has to be
# stated by the run that performs it.


UNUSABLE_RECORDED_ANSWERS: dict[str, str] = {
    "a typo for a known id": 'init-agents = ["cluade"]\n',
    "a known id beside an unknown one": 'init-agents = ["claude", "windsurf"]\n',
    "numbers rather than ids": "init-agents = [1, 2]\n",
    "a bare string rather than a list": 'init-agents = "claude"\n',
    "a number rather than a list": "init-agents = 42\n",
}
"""Every `init-agents` value smoke round 7 reached the uninstall through."""


def record(project_dir: Path, line: str) -> None:
    """Append a settings line to the project's `.lore/config.toml`."""
    config = project_dir / ".lore" / "config.toml"
    config.write_text(config.read_text(encoding="utf-8") + line, encoding="utf-8")


@pytest.mark.parametrize(
    "line",
    list(UNUSABLE_RECORDED_ANSWERS.values()),
    ids=list(UNUSABLE_RECORDED_ANSWERS),
)
class TestAnUnusableRecordedAnswerIsNotAnAnswer:
    """A config Lore cannot understand must never authorise a destructive act."""

    def test_the_agent_directory_is_not_emptied(self, runner, hand_copied, line):
        record(hand_copied, line)

        init(runner)

        assert entries(hand_copied, CLAUDE_SKILLS) == set(current_skill_ids())

    def test_the_instruction_file_survives(self, runner, hand_copied, line):
        record(hand_copied, line)

        init(runner)

        assert (hand_copied / "CLAUDE.md").is_file()

    def test_the_evidence_decides_instead_and_is_recorded(
        self, runner, hand_copied, line
    ):
        record(hand_copied, line)

        init(runner)

        config = (hand_copied / ".lore" / "config.toml").read_text(encoding="utf-8")
        assert 'init-agents = ["claude"]' in config

    def test_the_unusable_value_is_still_reported_on_stderr(
        self, runner, hand_copied, line, monkeypatch
    ):
        """Rejecting the value silently would leave nobody anything to fix."""
        import lore.config

        # The warning fires once per process and this suite shares one, so the
        # latch is cleared to ask about *this* run rather than an earlier one.
        monkeypatch.setattr(lore.config, "_warned", False)
        record(hand_copied, line)

        result = init(runner)

        assert "init-agents" in result.stderr


