class TestAnOlderReleaseTouchedTheProjectSince:
    """A manifest is a record of one run, not proof of what is on disk.

    Rolling back to an older `lore` and re-initialising reinstalls the retired
    skills and rewrites two current ones with older text. The manifest that the
    newer release then reads mentions none of it.
    """

    OLDER_INQUEST = b"# inquest\n\nThe text a release before this one shipped.\n"

    @pytest.fixture()
    def rolled_back(self, runner, legacy, legacy_table, table_rows):
        """Upgraded, then re-initialised by a release that predates the manifest."""
        stale = {}
        for current in ALIASED:
            retired = retired_alias(current)
            source = legacy / LORE_SKILLS / retired
            stale[retired] = {
                path.relative_to(source).as_posix(): path.read_bytes()
                for path in sorted(source.rglob("*"))
                if path.is_file()
            }

        init(runner, "--agent", "none", "--skills", "all", "--yes")

        # What the older binary put back: its own skill set, and its own text
        # over a skill this release still ships — bytes the historical table
        # records for that path, and the manifest just written does not.
        for retired, files in stale.items():
            for within, content in files.items():
                target = legacy / LORE_SKILLS / retired / within
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(content)
        (legacy / LORE_SKILLS / "inquest" / "SKILL.md").write_bytes(self.OLDER_INQUEST)
        table_rows[f"{LORE_SKILLS}/inquest/SKILL.md"].append(
            manifest.bytes_digest(self.OLDER_INQUEST)
        )
        legacy_table(table_rows)
        return legacy

    def test_the_reinstalled_retired_skills_are_removed(self, runner, rolled_back):
        init(runner, "--agent", "none", "--skills", "all", "--yes")

        for current in ALIASED:
            assert not (rolled_back / LORE_SKILLS / retired_alias(current)).exists()

    def test_a_current_skill_at_older_shipped_text_is_replaced(
        self, runner, rolled_back
    ):
        target = rolled_back / LORE_SKILLS / "inquest" / "SKILL.md"

        output = init(runner, "--agent", "none", "--skills", "all", "--yes").output

        assert target.read_bytes() != self.OLDER_INQUEST
        assert shown(f"{LORE_SKILLS}/inquest/SKILL.md") not in kept(output)


