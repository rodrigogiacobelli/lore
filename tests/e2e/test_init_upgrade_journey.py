#
# Smoke round 7, N5. The legacy fallback admits a path only when its bytes match
# one Lore shipped, so an edited **current** skill is admitted by nothing —
# editing it is the disqualification. The run then reported
#
#     ! Kept  skills/start-quest/SKILL.md
#             not installed by Lore
#
# about a file the previous release installed. The two edited *retired* skills
# in the same run get the true wording, because Lane L widened the fallback for
# them; a current path had no such route. Same false-statement shape as round
# 6's F8, which was fixed on the manifest path and not on this one.


class TestAnEditedCurrentSkillIsNotDisowned:
    """Whose file it is and whose bytes they are are two questions.

    Round 7's N5 was the first answered with the second: an edited current
    skill on a legacy project read `not installed by Lore`. Under the ownership
    ruling only the first question is ever asked, and the answer here is Lore's
    — so the file is taken back rather than described.
    """

    @pytest.fixture()
    def edited(self, hand_copied) -> Path:
        target = hand_copied / CLAUDE_SKILLS / "inquest" / "SKILL.md"
        assert target.is_file(), "inquest is not a current skill in this fixture"
        target.write_text("# mine now\n", encoding="utf-8")
        return hand_copied

    def test_the_run_no_longer_says_lore_never_installed_it(self, runner, edited):
        output = init(runner).output

        assert f"{CLAUDE_SKILLS}/inquest/SKILL.md" not in kept(output)
        assert reconcile.NOT_INSTALLED_BY_LORE not in output

    def test_it_is_taken_back_rather_than_reported(self, runner, edited):
        init(runner)

        target = edited / CLAUDE_SKILLS / "inquest" / "SKILL.md"
        assert target.read_text(encoding="utf-8") != "# mine now\n"

    def test_the_row_says_where_a_skill_of_their_own_belongs(self, runner, edited):
        summary = init(runner, "--dry-run").output
        row = next(
            line
            for line in summary.splitlines()
            if f"{CLAUDE_SKILLS}/inquest/SKILL.md" in line
        )
        assert reconcile.EDIT_DISCARDED in row
        assert CLAUDE_SKILLS in row.split()[-1]

    def test_a_file_lore_never_shipped_still_reads_as_not_installed(
        self, runner, hand_copied
    ):
        """The wording still distinguishes the two cases it exists to
        distinguish: a path Lore installs to, holding a file it never put
        there."""
        mine = hand_copied / CLAUDE_SKILLS / "inquest" / "NOTES.md"
        mine.write_text("mine\n", encoding="utf-8")

        init(runner)

        assert mine.read_text(encoding="utf-8") == "mine\n"


