class TestAnUnstatedTotalUninstallIsRefused:
    """Deselecting every agent is destructive, so the run that does it says so.

    The empty selection recorded in `.lore/config.toml` used to be the second
    way of stating it. It is not a statement about *this* run — it is a value
    in a file, and smoke round 7 wrote one there by accident, twice, through a
    fail-soft default. So the recorded answer alone now stops, and the flag
    that means it goes ahead.
    """

    @pytest.fixture()
    def recorded_empty(self, hand_copied) -> Path:
        record(hand_copied, "init-agents = []\n")
        return hand_copied

    def run(self, runner, *args):
        from lore.cli import main

        return runner.invoke(main, ["init", *args])

    def test_the_run_stops(self, runner, recorded_empty):
        assert self.run(runner).exit_code == 1

    def test_nothing_is_removed(self, runner, recorded_empty):
        before = entries(recorded_empty, CLAUDE_SKILLS)

        self.run(runner)

        assert entries(recorded_empty, CLAUDE_SKILLS) == before
        assert before

    def test_the_message_names_the_flag_that_states_it(self, runner, recorded_empty):
        assert "--agent none" in self.run(runner).output

    def test_the_message_names_where_the_empty_selection_came_from(
        self, runner, recorded_empty
    ):
        output = self.run(runner).output

        assert "init-agents" in output
        assert "config.toml" in output

    def test_the_message_names_the_agent_it_would_have_dropped(
        self, runner, recorded_empty
    ):
        assert "claude" in self.run(runner).output

    def test_no_traceback_reaches_the_terminal(self, runner, recorded_empty):
        result = self.run(runner)

        assert "Traceback" not in result.output + result.stderr

    def test_stating_it_on_the_run_goes_ahead(self, runner, recorded_empty):
        result = self.run(runner, "--agent", "none", "--skills", "all", "--yes")

        assert result.exit_code == 0, result.output
        assert entries(recorded_empty, CLAUDE_SKILLS) == set()

    def test_the_flag_that_keeps_the_agent_also_goes_ahead(
        self, runner, recorded_empty
    ):
        result = self.run(runner, "--agent", "claude", "--skills", "all", "--yes")

        assert result.exit_code == 0, result.output
        assert entries(recorded_empty, CLAUDE_SKILLS) == set(current_skill_ids())

    def test_a_dry_run_shows_the_refusal_beside_the_removals(
        self, runner, recorded_empty
    ):
        result = self.run(runner, "--dry-run")

        assert "--agent none" in result.output
        assert "Remove" in result.output

    def test_a_project_with_nothing_installed_for_an_agent_is_untouched(
        self, runner, legacy
    ):
        """No evidence, nothing to uninstall — the guard has no reason to fire."""
        record(legacy, "init-agents = []\n")

        result = self.run(runner)

        assert result.exit_code == 0, result.output
        assert entries(legacy, LORE_SKILLS) == set(current_skill_ids())

    def test_a_second_run_after_a_stated_uninstall_is_not_refused(
        self, runner, recorded_empty
    ):
        """The steady state a stated `--agent none` leaves behind still runs."""
        self.run(runner, "--agent", "none", "--skills", "all", "--yes")

        result = self.run(runner)

        assert result.exit_code == 0, result.output

    def test_the_python_api_refuses_the_same_plan(self, runner, recorded_empty):
        from lore import api

        before = entries(recorded_empty, CLAUDE_SKILLS)
        plan = api.plan_init(project_root=recorded_empty)
        with pytest.raises(ValueError) as raised:
            api.apply_init(plan)

        assert "--agent none" in str(raised.value)
        assert entries(recorded_empty, CLAUDE_SKILLS) == before


