"""E2E tests for the journey a real published release leaves behind.

Spec: conceptual-workflows-init-reconcile
(lore codex show conceptual-workflows-init-reconcile)

`tests/e2e/test_init_reconcile.py` covers the upgrade a project reaches by
passing every flag. This file covers the upgrade nobody passes flags to, which
is the one an AI coding agent performs: `lore init` through a pipe, with no
terminal to prompt at and no answer recorded in `.lore/config.toml` — because
no release before this one wrote any.

The project under test is built the way the pre-manifest releases left one, and
then the historical-hash table is told what those bytes were. Both are
constructed rather than installed: no previously released wheel is available to
a test run, and `reconcile._read_legacy_payload` is the seam that module
documents for exactly this. Everything downstream of the table — the walk, the
hash test, the removals, the pruning — is the real thing.

Per decisions-006-no-seed-content-tests nothing here pins the wording of a file
under `src/lore/defaults/`. Skill ids and retirement successors are read from
the catalogue at run time.
"""

from __future__ import annotations


import shutil
from pathlib import Path

import pytest
from click.testing import CliRunner

from lore import manifest, reconcile, skills


CLAUDE_SKILLS = ".claude/skills"
LORE_SKILLS = ".lore/skills"
AGENT_DOC = ".lore/LORE-AGENT.md"

OLD_AGENT_DOC = "# Lore\n\nThe agent instructions a release before this one shipped.\n"
OLD_SKILLS_GITIGNORE = "# Auto-generated by `lore init`.\nexplore-codex/\nnew-doctrine/\n"


# ---------------------------------------------------------------------------
# Catalogue lookups — structure, never wording
# ---------------------------------------------------------------------------


def retired_alias(skill_id: str) -> str:
    """A retired skill id the catalogue records as having become *skill_id*."""
    ledger = skills.load_catalogue().get("retired", {})
    aliases = sorted(old for old, row in ledger.items() if row["into"] == skill_id)
    assert aliases, f"the catalogue records no retired skill that became {skill_id}"
    return aliases[0]


def ledger_successor(skill_id: str) -> str:
    """The skill the catalogue says replaced *skill_id*."""
    retirement = skills.retirement_for(skill_id)
    assert retirement is not None, f"{skill_id} is not in the retirement ledger"
    return retirement.into


def current_skill_ids() -> tuple[str, ...]:
    """Every skill this release ships, from the catalogue."""
    return tuple(sorted(skills.skills_in_families(skills.family_ids())))


ALIASED = ("update-doctrine", "retrieve-memory", "store-memory")
"""The current skills the fixtures rewind — a rename, a merge, and a merge that
ships reference files, which is what puts a nested directory in the sweep."""


# ---------------------------------------------------------------------------
# Running the CLI
# ---------------------------------------------------------------------------


def init(runner: CliRunner, *args: str):
    """Run `lore init` with *args* and assert it succeeded."""
    from lore.cli import main

    result = runner.invoke(main, ["init", *args])
    assert result.exit_code == 0, result.output
    return result


def entries(project_dir: Path, root: str) -> set[str]:
    """The directory names directly under *root*, excluding dotfiles."""
    base = project_dir / root
    if not base.is_dir():
        return set()
    return {child.name for child in base.iterdir() if not child.name.startswith(".")}


def removals(output: str) -> dict[str, str | None]:
    """Every ``Removed <path> — <reason>`` line, as ``path -> reason``."""
    reported: dict[str, str | None] = {}
    for line in output.splitlines():
        parts = line.split()
        if parts[:1] != ["Removed"]:
            continue
        reason = line.split("—", 1)[1].strip() if "—" in line else None
        reported[parts[1]] = reason
    return reported


def kept(output: str) -> dict[str, str | None]:
    """Every ``! Kept <path>`` report, as ``path -> the detail line under it``."""
    lines = output.splitlines()
    reported: dict[str, str | None] = {}
    for index, line in enumerate(lines):
        parts = line.split()
        if parts[:2] != ["!", "Kept"]:
            continue
        follower = lines[index + 1].strip() if index + 1 < len(lines) else ""
        detail = (
            follower if follower and not follower.startswith(("!", "Removed")) else None
        )
        reported[parts[2]] = detail
    return reported


def written(output: str) -> set[str]:
    """Every path a run reported creating or updating."""
    return {
        line.split()[1]
        for line in output.splitlines()
        if line.split()[:1] in (["Created"], ["Updated"])
    }


def shown(path: str) -> str:
    """A repo-relative path as the applied-run messages name it."""
    return path[len(".lore/") :] if path.startswith(".lore/") else path


PLAN_LABELS = ("Create", "Section", "Overwrite", "Remove", "Conflict", "Seed")


def plan_paths(output: str) -> set[str]:
    """Every path the plan's listing names, whichever block it is in."""
    return {
        line.split()[1]
        for line in output.splitlines()
        if line.startswith("  ") and line.split()[:1] and line.split()[0] in PLAN_LABELS
    }


# ---------------------------------------------------------------------------
# Building the project a pre-manifest release left behind
# ---------------------------------------------------------------------------


def age_skills(project_dir: Path, aliases: dict[str, str]) -> None:
    """Rename each installed skill directory to the retired id that became it."""
    for current, retired in aliases.items():
        source = project_dir / LORE_SKILLS / current
        assert source.is_dir(), f"{current} is not installed at {source}"
        shutil.move(str(source), str(project_dir / LORE_SKILLS / retired))


def strip_recorded_answers(project_dir: Path) -> None:
    """Remove the four recorded answers, as a pre-0.10.0 `config.toml` has none."""
    config = project_dir / ".lore" / "config.toml"
    kept_lines = [
        line
        for line in config.read_text(encoding="utf-8").splitlines(keepends=True)
        if not line.split("=", 1)[0].strip().startswith("init-")
    ]
    config.write_text("".join(kept_lines), encoding="utf-8")


def hash_tree(project_dir: Path, root: str) -> dict[str, list[str]]:
    """The historical-hash rows for everything under *root*, keyed as installed."""
    base = project_dir / root
    rows: dict[str, list[str]] = {}
    for candidate in sorted(base.rglob("*")):
        if not candidate.is_file():
            continue
        within = candidate.relative_to(base).as_posix()
        rows[f"{LORE_SKILLS}/{within}"] = [manifest.file_digest(candidate)]
    return rows


@pytest.fixture()
def fresh(tmp_path, monkeypatch):
    """An empty directory that is the working directory for the whole test."""
    monkeypatch.chdir(tmp_path)
    return tmp_path


@pytest.fixture()
def legacy_table(monkeypatch):
    """Substitute the packaged historical-hash table for one test."""

    def install(files: dict[str, list[str]]) -> None:
        payload = {"legacy_hashes_version": 1, "files": files}
        monkeypatch.setattr(reconcile, "_read_legacy_payload", lambda: payload)
        reconcile.load_legacy_hashes.cache_clear()

    yield install
    reconcile.load_legacy_hashes.cache_clear()


@pytest.fixture()
def table_rows():
    """The historical-hash rows the test has told the table about, so far."""
    return {}


@pytest.fixture()
def legacy(runner, fresh, legacy_table, table_rows):
    """A project in the state a release before the manifest left it.

    Installed under `.lore/skills/` on the pre-consolidation skill ids, with no
    `.install-manifest.json`, no recorded answers and its own agent doc and
    skills gitignore at bytes only the historical table knows.
    """
    init(runner, "--agent", "none", "--skills", "all", "--access", "native", "--yes")
    age_skills(fresh, {current: retired_alias(current) for current in ALIASED})

    (fresh / AGENT_DOC).write_text(OLD_AGENT_DOC, encoding="utf-8")
    (fresh / LORE_SKILLS / ".gitignore").write_text(
        OLD_SKILLS_GITIGNORE, encoding="utf-8"
    )
    (fresh / ".lore" / ".install-manifest.json").unlink()
    strip_recorded_answers(fresh)

    table_rows.update(hash_tree(fresh, LORE_SKILLS))
    table_rows[AGENT_DOC] = [manifest.file_digest(fresh / AGENT_DOC)]
    legacy_table(table_rows)
    return fresh


@pytest.fixture()
def hand_copied(legacy):
    """`legacy`, with `.lore/skills/` copied into `.claude/skills/`.

    The pre-feature `GETTING-STARTED.md` told people to run
    `cp -r .lore/skills/. .claude/skills/`, so this is the layout the
    documentation produced and the one the upgrade has to survive.
    """
    shutil.copytree(legacy / LORE_SKILLS, legacy / CLAUDE_SKILLS)
    return legacy


