class TestNoAgentAnswerNeverUninstalls:
    """`lore init` with no flags, no terminal and no recorded answer.

    "Nobody said which agents" is not "the user asked for no agent". The first
    is the state every pre-0.10.0 project is in; reading it as the second
    deletes every skill the documented `cp -r` put in `.claude/skills/`.
    """

    def test_the_agent_directory_is_not_emptied(self, runner, hand_copied):
        init(runner)
        assert entries(hand_copied, CLAUDE_SKILLS)

    def test_every_current_skill_is_installed_into_the_agent_directory(
        self, runner, hand_copied
    ):
        init(runner)
        assert entries(hand_copied, CLAUDE_SKILLS) == set(current_skill_ids())

    def test_every_retired_skill_is_gone_from_the_agent_directory(
        self, runner, hand_copied
    ):
        init(runner)
        installed = entries(hand_copied, CLAUDE_SKILLS)
        for current in ALIASED:
            assert retired_alias(current) not in installed

    def test_the_agent_instruction_file_is_written(self, runner, hand_copied):
        init(runner)
        assert (hand_copied / "CLAUDE.md").is_file()

    def test_the_derived_answer_is_recorded_so_it_is_derived_once(
        self, runner, hand_copied
    ):
        init(runner)
        config = (hand_copied / ".lore" / "config.toml").read_text(encoding="utf-8")
        assert 'init-agents = ["claude"]' in config

    def test_an_explicit_none_still_uninstalls(self, runner, hand_copied):
        init(runner, "--agent", "none", "--skills", "all", "--yes")
        assert entries(hand_copied, CLAUDE_SKILLS) == set()

    def test_a_project_with_no_agent_directory_installs_under_lore_skills(
        self, runner, legacy
    ):
        init(runner)
        assert entries(legacy, LORE_SKILLS) == set(current_skill_ids())
        assert not (legacy / "CLAUDE.md").exists()

    def test_a_directory_holding_only_the_users_own_skills_is_not_evidence(
        self, runner, legacy
    ):
        mine = legacy / CLAUDE_SKILLS / "my-own-skill" / "SKILL.md"
        mine.parent.mkdir(parents=True)
        mine.write_text("mine\n", encoding="utf-8")

        init(runner)

        assert entries(legacy, CLAUDE_SKILLS) == {"my-own-skill"}
        assert mine.read_text(encoding="utf-8") == "mine\n"

    def test_a_fresh_project_still_selects_no_agent(self, runner, fresh):
        init(runner)
        assert not (fresh / "CLAUDE.md").exists()
        assert entries(fresh, LORE_SKILLS) == set(current_skill_ids())


class TestARemovalSaysWhichKindItIs:
    """A retirement and an uninstall must not read identically.

    "Retired — port your edits into its successor" and "this file moved to
    another directory" call for opposite responses from the reader, so a
    removal report that renders both as a bare path tells nobody anything.
    """

    def test_an_uninstall_names_where_the_skill_went(self, runner, hand_copied):
        output = init(runner, "--agent", "none", "--skills", "all", "--yes").output

        # `inquest` is current, not retired: it is leaving `.claude/skills/`
        # only because the answer moved the install root.
        reported = removals(output)
        moved = f"{CLAUDE_SKILLS}/inquest/SKILL.md"
        assert moved in reported, reported
        assert reported[moved] is not None
        assert LORE_SKILLS in reported[moved]

    def test_a_retirement_still_names_its_reason(self, runner, hand_copied):
        output = init(runner, "--agent", "none", "--skills", "all", "--yes").output
        retired = retired_alias("update-doctrine")
        reported = removals(output)

        assert reported[f"{CLAUDE_SKILLS}/{retired}/SKILL.md"]

    def test_a_retirement_names_its_successor(self, runner, hand_copied):
        output = init(runner, "--agent", "none", "--skills", "all", "--yes").output
        retired = retired_alias("update-doctrine")
        reason = removals(output)[f"{CLAUDE_SKILLS}/{retired}/SKILL.md"]

        assert ledger_successor(retired) in reason


