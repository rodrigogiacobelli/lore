class TestThePlanNamesEveryFileTheRunWrites:
    """`--help` promises the plan lists every file, and the confirm gate shows it.

    The seeded `default/` trees are about seventy files the run overwrites in
    place. A plan that omits them asks for consent to something else.
    """

    def test_the_plan_names_the_seeded_default_trees(self, runner, legacy):
        output = init(runner, "--dry-run").output
        for tree in ("knights/default", "artifacts/default", "doctrines/default"):
            assert tree in output, output

    def test_the_plan_writes_nothing(self, runner, legacy):
        before = {
            path.relative_to(legacy).as_posix(): path.read_bytes()
            for path in sorted(legacy.rglob("*"))
            if path.is_file()
        }

        init(runner, "--dry-run")

        after = {
            path.relative_to(legacy).as_posix(): path.read_bytes()
            for path in sorted(legacy.rglob("*"))
            if path.is_file()
        }
        assert after == before

    def test_every_path_the_run_writes_appeared_in_the_plan(self, runner, legacy):
        # The plan names paths from the repository root; an applied run names a
        # path inside `.lore/` relative to it. `shown` is that difference.
        planned = {shown(path) for path in plan_paths(init(runner, "--dry-run").output)}
        # "Created .lore/ directory" names the directory the rest go into, not
        # a file — the plan is a list of files.
        applied = written(init(runner).output) - {".lore/"}

        assert sorted(applied - planned) == []


class TestAFileTheReleaseNoLongerShips:
    """A seeded `default/` tree is Lore's own, so a file it stopped shipping is stale.

    The two oldest releases seeded artifacts at paths this one renamed. Left
    there, they fail `lore health` against a schema that has moved on.
    """

    def test_it_is_removed_from_the_seeded_tree(self, runner, legacy):
        orphan = legacy / ".lore" / "artifacts" / "default" / "codex" / "CODEX.md"
        orphan.parent.mkdir(parents=True, exist_ok=True)
        orphan.write_text("stale\n", encoding="utf-8")

        init(runner)

        assert not orphan.exists()

    def test_the_removal_is_reported(self, runner, legacy):
        orphan = legacy / ".lore" / "knights" / "default" / "gone.md"
        orphan.write_text("stale\n", encoding="utf-8")

        output = init(runner).output

        assert "knights/default/gone.md" in removals(output)

    def test_a_tree_of_the_users_own_is_untouched(self, runner, legacy):
        mine = legacy / ".lore" / "knights" / "team" / "reviewer.md"
        mine.parent.mkdir(parents=True, exist_ok=True)
        mine.write_text("ours\n", encoding="utf-8")

        init(runner)

        assert mine.read_text(encoding="utf-8") == "ours\n"

    def test_health_is_clean_after_the_prune(self, runner, legacy):
        from lore.cli import main

        orphan = (
            legacy
            / ".lore"
            / "artifacts"
            / "default"
            / "codex"
            / "technical"
            / "database"
            / "schemas"
            / "tasks.md"
        )
        orphan.parent.mkdir(parents=True, exist_ok=True)
        orphan.write_text(
            "---\nid: art-stale\ntitle: Stale\nrelated: []\n---\n\nStale.\n",
            encoding="utf-8",
        )

        init(runner)

        result = runner.invoke(main, ["health"])
        assert result.exit_code == 0, result.output
